/**
 * Spaced review scheduling — transparent deterministic algorithm.
 *
 * Base intervals (days): [1, 3, 7, 16, 35, 75].
 * - First successful review: 1 day.
 * - Correct, unassisted: advance one interval step (ease ±0.1 bonus unused for simplicity,
 *   ease multiplies the interval).
 * - Correct but assisted: repeat the same step (schedule sooner).
 * - Incorrect: drop two steps (minimum 1 day) and count a lapse.
 * - Interval = round(base[step] * ease), clamped to [0.5, 180] days.
 * - ease starts 2.3, +0.1 per clean success (max 3.0), -0.3 per lapse (min 1.3).
 *
 * The schedule is persisted per concept; review questions are re-generated by variant,
 * never the identical stored answer.
 */
import { ReviewRecord } from '../storage/repositories';

export const REVIEW_INTERVALS_DAYS = [1, 3, 7, 16, 35, 75];
export const DAY_MS = 86_400_000;

export function initialReview(conceptId: string, now = new Date()): ReviewRecord {
  return {
    conceptId,
    dueAt: new Date(now.getTime() + DAY_MS).toISOString(),
    intervalDays: 1,
    ease: 2.3,
    reps: 0,
    lapses: 0,
    updatedAt: now.toISOString(),
  };
}

export function stepFromInterval(days: number): number {
  let best = 0;
  for (let i = 0; i < REVIEW_INTERVALS_DAYS.length; i++) {
    if (REVIEW_INTERVALS_DAYS[i] <= days + 0.01) best = i;
  }
  return best;
}

export function scheduleReview(
  rec: ReviewRecord,
  result: { correct: boolean; assisted: boolean },
  now = new Date(),
): ReviewRecord {
  let step = stepFromInterval(rec.intervalDays);
  let ease = rec.ease;
  let lapses = rec.lapses;
  if (result.correct) {
    if (!result.assisted) {
      step = Math.min(step + 1, REVIEW_INTERVALS_DAYS.length - 1);
      ease = Math.min(3.0, Number((ease + 0.1).toFixed(2)));
    }
    // assisted correct: repeat the same step
  } else {
    step = Math.max(0, step - 2);
    ease = Math.max(1.3, Number((ease - 0.3).toFixed(2)));
    lapses += 1;
  }
  const intervalDays = Math.min(180, Math.max(0.5, Math.round(REVIEW_INTERVALS_DAYS[step] * ease * 10) / 10));
  return {
    ...rec,
    intervalDays,
    ease,
    reps: rec.reps + 1,
    lapses,
    lastResult: result.correct ? 'correct' : 'incorrect',
    dueAt: new Date(now.getTime() + intervalDays * DAY_MS).toISOString(),
    updatedAt: now.toISOString(),
  };
}

/** Schedule the first review after a lesson is completed. */
export function scheduleAfterLesson(conceptId: string, now = new Date()): ReviewRecord {
  const rec = initialReview(conceptId, now);
  return rec;
}

export function isDue(rec: ReviewRecord, now = new Date()): boolean {
  return Date.parse(rec.dueAt) <= now.getTime();
}

export function dueReviews(reviews: ReviewRecord[], now = new Date()): ReviewRecord[] {
  return reviews.filter((r) => isDue(r, now)).sort((a, b) => Date.parse(a.dueAt) - Date.parse(b.dueAt));
}

/** Days until due, for display. Negative => overdue. */
export function daysUntilDue(rec: ReviewRecord, now = new Date()): number {
  return Math.ceil((Date.parse(rec.dueAt) - now.getTime()) / DAY_MS);
}

export function nextReviewDate(reviews: ReviewRecord[], now = new Date()): string | null {
  const upcoming = reviews.filter((r) => !isDue(r, now)).sort((a, b) => Date.parse(a.dueAt) - Date.parse(b.dueAt));
  return upcoming[0]?.dueAt ?? null;
}
